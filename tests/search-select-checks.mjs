import assert from 'node:assert/strict';

export async function checkSearchSelectors(page) {
  const combo=()=>page.getByRole('combobox',{name:'Customer',exact:true});
  const dialog=()=>page.getByRole('dialog',{name:'Add job',exact:true});
  const options=()=>page.getByRole('listbox',{name:'Customer options',exact:true}).getByRole('option');
  async function dimensions(expected){
    const select=await combo().locator('..').boundingBox();
    const input=await page.getByLabel('Job / site title',{exact:true}).boundingBox();
    const status=await page.getByLabel('Status',{exact:true}).boundingBox();
    assert(Math.abs(select.height-input.height)<=1,'Searchable selection height must match the adjacent text input');
    assert(Math.abs(select.height-status.height)<=1,'Searchable selection height must match the native enum select');
    assert(Math.abs(select.height-expected)<=1,`Expected ${expected}px control height, got ${select.height}`);
    assert(Math.abs(select.width-input.width)<=1,'Equal grid columns must produce equal input widths');
  }
  await dimensions(34);
  await page.getByLabel('Job / site title',{exact:true}).fill('Required validation check');
  await page.getByRole('button',{name:'Save record',exact:true}).click();
  assert(await dialog().isVisible(),'Unselected required customer cannot submit the form');
  assert.equal(await combo().evaluate(el=>el.validity.valid),false);
  await combo().fill('No customer with this exact search');
  await page.getByText('No matching records.',{exact:true}).waitFor();
  await combo().press('Escape');
  assert(await dialog().isVisible(),'Escape closes only the open selection menu');
  assert.equal(await combo().getAttribute('aria-expanded'),'false');
  await combo().fill('Lookup Customer');
  await options().nth(24).waitFor();
  assert.equal(await options().count(),25,'Only one server page is initially shown');
  await page.screenshot({path:'tests/artifacts/selector-desktop.png',fullPage:true});
  await page.getByRole('button',{name:'Load more',exact:true}).click();
  await options().nth(49).waitFor();
  await page.getByRole('button',{name:'Load more',exact:true}).click();
  await options().nth(64).waitFor();
  await options().filter({hasText:'Lookup Customer 065'}).click();
  assert.match(await combo().inputValue(),/Lookup Customer 065/);
  await combo().click();await combo().fill('not a committed selection');await combo().press('Escape');
  assert.match(await combo().inputValue(),/Lookup Customer 065/,'Uncommitted text must not replace the selected ID');
  await combo().fill('099000064');await options().first().waitFor();
  await combo().press('Home');await combo().press('Enter');
  assert.match(await combo().inputValue(),/Lookup Customer 064/,'Keyboard selection works with phone search');
  await page.getByRole('button',{name:'Clear Customer',exact:true}).click();
  assert.equal(await combo().inputValue(),'');
  assert.equal(await combo().evaluate(el=>el.validity.valid),false,'Clearing a required value restores required validation');
  const failure=async route=>{const url=new URL(route.request().url());if(url.searchParams.get('resource')==='customers'&&url.searchParams.get('q')==='error-test'){await route.fulfill({status:503,contentType:'application/json',body:JSON.stringify({error:'Temporary lookup failure'})});}else await route.continue();};
  await page.route('**/api/lookup?**',failure);
  await combo().fill('error-test');await page.getByText('Temporary lookup failure',{exact:false}).waitFor();
  await page.unroute('**/api/lookup?**',failure);
  await page.getByRole('button',{name:'Retry',exact:true}).click();
  await page.getByText('No matching records.',{exact:true}).waitFor();
  await combo().press('Escape');
  await page.getByRole('button',{name:'Cancel',exact:true}).click();

  await page.getByRole('button',{name:'Comfortable',exact:true}).click();
  await page.getByRole('button',{name:'Add job',exact:true}).click();
  await dimensions(43);
  await page.getByRole('button',{name:'Cancel',exact:true}).click();
  await page.getByRole('button',{name:'Compact',exact:true}).click();
  await page.setViewportSize({width:390,height:844});
  await page.getByRole('button',{name:'Add job',exact:true}).click();
  await dimensions(42);
  await combo().fill('Lookup Customer');await options().nth(24).waitFor();
  const popup=await page.locator('.lookup-menu').boundingBox();
  assert(popup.x>=0&&popup.x+popup.width<=390,'Popup fits mobile width');
  assert(popup.y>=0&&popup.y+popup.height<=844,'Popup fits mobile height');
  await page.screenshot({path:'tests/artifacts/selector-mobile.png',fullPage:true});
  await combo().press('Escape');await page.getByRole('button',{name:'Cancel',exact:true}).click();
  await page.setViewportSize({width:1280,height:720});
  await page.getByRole('button',{name:'Toggle color theme',exact:true}).click();
  await page.getByRole('button',{name:'Add job',exact:true}).click();
  await combo().fill('Lookup Customer');await options().nth(24).waitFor();
  const rootColor=await page.locator('.admin-root').evaluate(el=>getComputedStyle(el).getPropertyValue('--surface').trim());
  const popupColor=await page.locator('.lookup-menu').evaluate(el=>getComputedStyle(el).backgroundColor);
  assert.equal(rootColor,'#19252e');assert.equal(popupColor,'rgb(25, 37, 46)','Portaled menu retains dark theme');
  await page.screenshot({path:'tests/artifacts/selector-dark.png',fullPage:true});
  await combo().press('Escape');await page.getByRole('button',{name:'Cancel',exact:true}).click();
  await page.getByRole('button',{name:'Toggle color theme',exact:true}).click();
  await page.setViewportSize({width:1440,height:900});
  await page.getByRole('button',{name:'Add job',exact:true}).click();
  console.log('PASS: searchable selections, later pages, keyboard/Escape, required validation, clear, error/retry, matching 34/43/42px controls, modal/mobile bounds, and dark theme.');
}
